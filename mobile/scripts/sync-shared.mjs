// Copies framework-free modules from the website (../src) into src/shared so
// the app uses the same validation rules, VAT maths and database types.
// Run after changing any of them on the web side: npm run sync-shared
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..', '..', 'src');
const out = join(here, '..', 'src', 'shared');

const files = {
  'types/database.ts': 'database.ts',
  'lib/vat.ts': 'vat.ts',
  'lib/vehicles/lookup.ts': 'lookup.ts',
  'lib/account/deletion.ts': 'deletion.ts',
  'lib/validation/auth.ts': 'validation/auth.ts',
  'lib/validation/request.ts': 'validation/request.ts',
  'lib/validation/vehicle.ts': 'validation/vehicle.ts',
  'lib/validation/vehicle-care.ts': 'validation/vehicle-care.ts',
  'lib/validation/review.ts': 'validation/review.ts',
};

// Web '@/...' imports that the copied files use, rewritten relative to src/shared.
const rewrites = {
  '@/lib/vehicles/lookup': '../lookup',
  '@/types/database': '../database',
};

mkdirSync(join(out, 'validation'), { recursive: true });
for (const [from, to] of Object.entries(files)) {
  let src = readFileSync(join(web, from), 'utf8').replace(/^'use client';\r?\n\r?\n?/, '');
  for (const [a, b] of Object.entries(rewrites)) {
    const target = to.includes('/') ? b : b.replace('../', './');
    src = src.split(`'${a}'`).join(`'${target}'`);
  }
  writeFileSync(join(out, to), `// GENERATED by scripts/sync-shared.mjs from src/${from} — edit the web file, not this one.\n${src}`);
  console.log(`synced ${from} -> src/shared/${to}`);
}
